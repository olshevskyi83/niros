@dataclass(frozen=True)
class AssessmentDomain:
    domain_id: str
    title: str
    purpose: str
    pattern_ids: tuple[str, ...]
    semantic_fact_categories: tuple[str, ...]
    suggested_assessment_tools: tuple[str, ...]
    fingerprint_dimensions: tuple[str, ...]
    priority: int


def _domain(
    domain_id: str,
    title: str,
    purpose: str,
    pattern_ids: tuple[str, ...],
    semantic_fact_categories: tuple[str, ...],
    suggested_assessment_tools: tuple[str, ...],
    fingerprint_dimensions: tuple[str, ...],
    priority: int,
) -> AssessmentDomain:
    return AssessmentDomain(
        domain_id=domain_id,
        title=title,
        purpose=purpose,
        pattern_ids=pattern_ids,
        semantic_fact_categories=semantic_fact_categories,
        suggested_assessment_tools=suggested_assessment_tools,
        fingerprint_dimensions=fingerprint_dimensions,
        priority=priority,
    )


