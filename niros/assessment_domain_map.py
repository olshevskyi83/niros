def get_assessment_domain(domain_id: str) -> AssessmentDomain | None:
    return build_assessment_domain_map().get(domain_id)


def all_assessment_domains() -> tuple[AssessmentDomain, ...]:
    domain_map = build_assessment_domain_map()
    return tuple(domain_map[domain_id] for domain_id in CORE_DOMAIN_IDS)


def domain_map_contains_diagnostic_language(domain: AssessmentDomain) -> bool:
    text = f"{domain.title} {domain.purpose}".lower()
    return any(phrase in text for phrase in FORBIDDEN_DIAGNOSTIC_PHRASES)
